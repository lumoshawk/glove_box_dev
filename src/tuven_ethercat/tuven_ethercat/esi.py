"""Turn the vendor ESI file into this package's ESI excerpt and drive file.

  ref/TUVEN_ESI_V7.6.xml  --extract-->  esi/TUVEN_D1616BP.xml  --drive-->  config/drives/d1616bp.yaml

The vendor ESI describes 44 devices; extract() keeps the vendor block and the one device we own, drive_from_esi()
reads that device's sync managers and PDOs into the yaml the generic slave plugin needs. Run `gen_drive` to
rewrite both files, `gen_drive --check` to fail when they are out of date (the pytest suite does the same).
"""
import argparse
import os
import xml.etree.ElementTree as ET

import yaml

MODEL = 'D1616BP'
PACKAGE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ESI_PATH = os.path.join(PACKAGE_DIR, 'esi', 'TUVEN_D1616BP.xml')
DRIVE_PATH = os.path.join(PACKAGE_DIR, 'config', 'drives', 'd1616bp.yaml')
VENDOR_ESI = os.path.join(os.path.dirname(os.path.dirname(PACKAGE_DIR)), 'ref', 'TUVEN_ESI_V7.6.xml')

ET.register_namespace('xsi', 'http://www.w3.org/2001/XMLSchema-instance')

HEADER = '''# Drive TYPE definition of the TUVEN {name}, generated by `ros2 run tuven_ethercat gen_drive`
# from esi/TUVEN_D1616BP.xml (an excerpt of ref/TUVEN_ESI_V7.6.xml). Do not edit: change the ESI and regenerate.
# Channels are named out<n> / in<n> after their CoE sub-index (Data Out<n> / Data In<n> in the ESI).
'''


class Hex(int):
    """Int that yaml writes as 0x...: indices and ids are hex everywhere in the manuals."""


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(
    Hex, lambda dumper, value: dumper.represent_scalar('tag:yaml.org,2002:int', f'0x{int(value):04X}'))


def number(text):
    """ESI numbers are decimal or '#x' hex."""
    text = text.strip()
    return int(text[2:], 16) if text.startswith('#x') else int(text)


def _find_device(root, model):
    for device in root.iter('Device'):
        if device.find('Type').text == model:
            return device
    raise ValueError(f'{model} is not in the ESI file')


def extract(source, model=MODEL):
    """ESI text with only `model` left in the vendor file, or raise if it is not there."""
    tree = ET.parse(source)
    root = tree.getroot()
    keep = _find_device(root, model)
    devices = root.find('Descriptions').find('Devices')
    for device in list(devices):
        if device is not keep:
            devices.remove(device)
    ET.indent(tree, space='  ')
    return ET.tostring(root, encoding='unicode', xml_declaration=False)


def drive_from_esi(path, model=MODEL):
    """The drive dict (vendor/product id, sync managers, PDO channels) read from an ESI file."""
    root = ET.parse(path).getroot()
    device = _find_device(root, model)
    sm = []
    for index, element in enumerate(device.findall('Sm')):
        control = number(element.get('ControlByte'))
        entry = {'index': index, 'type': 'output' if (control >> 2) & 3 == 1 else 'input'}
        # RxPdo / TxPdo are assigned to the process data sync managers (not the mailbox, mode bits 0-1 == 2)
        if control & 3 != 2:
            entry['pdo'] = 'rpdo' if entry['type'] == 'output' else 'tpdo'
            entry['watchdog'] = 'enable' if control & 0x40 else 'disable'
        sm.append(entry)
    drive = {
        'name': model,
        'vendor_id': Hex(number(root.find('Vendor').find('Id').text)),
        'product_id': Hex(number(device.find('Type').get('ProductCode'))),
        'revision': Hex(number(device.find('Type').get('RevisionNo'))),
        'assign_activate': Hex(0),
        'sm': sm,
        'rpdo': [],
        'tpdo': [],
    }
    for pdo in list(device.findall('RxPdo')) + list(device.findall('TxPdo')):
        receive = pdo.tag == 'RxPdo'
        channels, offset = [], 0
        for entry in pdo.findall('Entry'):
            bits = int(entry.find('BitLen').text)
            index = number(entry.find('Index').text)
            sub = number(entry.find('SubIndex').text) if entry.find('SubIndex') is not None else 0
            if entry.find('DataType') is not None and entry.find('DataType').text == 'BOOL':
                # the plugin addresses a bit by its byte plus a mask
                channel = {'name': f'{"out" if receive else "in"}{sub}', 'index': Hex(index), 'sub_index': sub,
                           'type': 'bool', 'mask': 1 << (offset % 8)}
            else:
                raise ValueError(f'{model}: {entry.find("Name").text} is not a BOOL entry; '
                                 'extend drive_from_esi for other types')
            channels.append(channel)
            offset += bits
        drive['rpdo' if receive else 'tpdo'].append({'index': Hex(number(pdo.find('Index').text)),
                                                     'sm': int(pdo.get('Sm')), 'channels': channels})
    return drive


def dump_drive(drive):
    return HEADER.format(name=drive['name']) + yaml.dump(
        drive, Dumper=_Dumper, default_flow_style=None, sort_keys=False, width=140)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--source', default=VENDOR_ESI, help='vendor ESI file (default: ref/TUVEN_ESI_V7.6.xml)')
    parser.add_argument('--model', default=MODEL)
    parser.add_argument('--check', action='store_true', help='exit 1 if the packaged files are out of date')
    args = parser.parse_args()

    esi_text = extract(args.source, args.model)
    tmp_path = ESI_PATH + '.tmp'
    with open(tmp_path, 'w', encoding='utf-8') as f:
        f.write(esi_text)
    try:
        drive_text = dump_drive(drive_from_esi(tmp_path, args.model))
    finally:
        os.remove(tmp_path)

    stale = []
    for path, text in ((ESI_PATH, esi_text), (DRIVE_PATH, drive_text)):
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if current != text:
            stale.append(path)
            if not args.check:
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(text)
    for path in stale:
        print(('out of date: ' if args.check else 'wrote ') + os.path.relpath(path, PACKAGE_DIR))
    if args.check and stale:
        raise SystemExit(1)
    if not stale:
        print('up to date')


if __name__ == '__main__':
    main()
